function prims(list: Prim[]) {
  return list.map((pr, i) => {
    if ('l' in pr) return <line key={i} x1={pr.l[0]} y1={pr.l[1]} x2={pr.l[2]} y2={pr.l[3]} />
    if ('d' in pr) return <line key={i} x1={pr.d[0]} y1={pr.d[1]} x2={pr.d[2]} y2={pr.d[3]} strokeDasharray="3 2.5" />
    if ('c' in pr) return <circle key={i} cx={pr.c[0]} cy={pr.c[1]} r={pr.c[2]} />
    return <rect key={i} x={pr.r[0]} y={pr.r[1]} width={pr.r[2]} height={pr.r[3]} rx={1.5} />
  })
}

// Pictograma animado: dos fotogramas que alternan (CSS .wod-frame-a/b en index.css).
export function Pictogram({ slug, className = '' }: { slug: string; className?: string }) {
  const key = (EXERCISES[slug] || EXERCISES.other).pict
  const { a, b } = P[key] || P.other
  const isStatic = a === b
  return (
    <svg
      viewBox="0 0 48 48"
      className={className}
      fill="none"
      stroke="currentColor"
      strokeWidth={2.4}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <g className={isStatic ? undefined : 'wod-frame-a'}>{prims(a)}</g>
      {!isStatic && <g className="wod-frame-b">{prims(b)}</g>}
    </svg>
  )
}
